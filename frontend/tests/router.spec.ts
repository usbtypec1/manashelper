import { expect, test } from '@playwright/test'
import { mockTelegram } from './telegram'

test('legacy links redirect, SPA navigation preserves the WebView, and history restores pages', async ({ page, request }) => {
  const fixture = await (await request.get('/_fixture/init-data?preferences=1&locale=en')).json()
  await mockTelegram(page, fixture)
  await page.goto('/app/?view=settings&launch=preserved#telegram-context')
  await expect(page).toHaveURL('/app/settings?launch=preserved#telegram-context')
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await page.evaluate(() => Object.assign(window, { sameWebView: true }))
  await page.getByRole('button', { name: 'Courses', exact: true }).click()
  await expect(page).toHaveURL('/app/courses')
  await expect(page.getByRole('combobox', { name: 'Choose a faculty', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('checkbox', { name: 'Exam grades', exact: true })).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('combobox', { name: 'Choose a faculty', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Terms of use and data processing' }).click()
  await expect(page).toHaveURL('/app/terms?lang=en&from=courses')
  await expect(page.getByRole('heading', { name: 'Terms of use and data processing' })).toBeVisible()
  await page.getByRole('link', { name: 'Back', exact: true }).click()
  await expect(page).toHaveURL('/app/courses')
  expect(await page.evaluate(() => (window as Window & { sameWebView?: boolean }).sameWebView)).toBe(true)
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Choose a faculty', exact: true })).toBeVisible()
})

test('achievement routes support direct entry, refresh and browser history', async ({ page, request }) => {
  const fixture = await (await request.get('/_fixture/init-data')).json()
  await mockTelegram(page, fixture)
  await page.goto('/app/leaderboard')
  await expect(page.getByRole('heading', { name: 'Лидерборд', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Лидерборд', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Моя коллекция', exact: true }).click()
  await expect(page).toHaveURL('/app/achievements')
  await expect(page.locator('button.achievement')).toHaveCount(15)
  await page.goBack()
  await expect(page).toHaveURL('/app/leaderboard')
  await expect(page.getByRole('heading', { name: 'Лидерборд', exact: true })).toBeVisible()
})

test('public terms deep links reload without authentication and old links keep locale', async ({ page }) => {
  await page.goto('/app/?view=terms&lang=ky')
  await expect(page).toHaveURL('/app/terms?lang=ky')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Колдонуучу келишими жана маалыматтарды иштетүү')
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Колдонуучу келишими жана маалыматтарды иштетүү')
})
