"""Persistence contracts; adapters share the caller's transaction with DB delegates."""

from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Protocol
from uuid import UUID

from ui_flows.domain.contracts import DeliveryStatus
from ui_flows.domain.delivery import ScreenDelivery
from ui_flows.domain.schema import FlowDocument
from ui_flows.domain.state import DialogState, Draft, PublishedFlow


class FlowStore(Protocol):
    def atomic(self) -> AbstractAsyncContextManager[None]: ...

    async def create(self, document: FlowDocument) -> Draft: ...

    async def get(self, flow_id: str, *, lock: bool = False) -> Draft: ...

    async def save_draft(self, document: FlowDocument, expected_revision: int) -> Draft: ...

    async def find_revision(self, flow_id: str, draft_revision: int) -> PublishedFlow | None: ...

    async def version(self, flow_id: str, version: int) -> PublishedFlow: ...

    async def published(self, flow_id: str) -> PublishedFlow: ...

    async def from_release(self, flow_id: str, release_id: int) -> PublishedFlow: ...

    async def add_version(
        self, draft: Draft, author_id: int, *, dependencies: dict[str, int] | None = None
    ) -> PublishedFlow: ...

    async def activate(self, flow_id: str, version: int) -> None: ...


class DialogStore(Protocol):
    def atomic(self) -> AbstractAsyncContextManager[None]: ...

    async def lock_chat(self, chat_id: int) -> None: ...

    async def active(self, chat_id: int) -> DialogState | None: ...

    async def get(self, session_id: UUID, *, lock: bool = False) -> DialogState: ...

    async def processed_by(self, update_id: int) -> UUID | None: ...

    async def processed_result(self, update_id: int) -> DialogState: ...

    async def create(self, state: DialogState) -> None: ...

    async def save(self, state: DialogState) -> None: ...

    async def record(
        self,
        state: DialogState,
        update_id: int,
        kind: str,
        from_step: str | None,
        outcome: str,
        *,
        result_state: DialogState | None = None,
    ) -> None: ...

    async def record_effect(self, state: DialogState, operation_id: UUID, from_step: str, outcome: str) -> None: ...


class DeliveryStore(Protocol):
    async def by_update(self, update_id: int) -> ScreenDelivery | None: ...
    async def by_operation(self, operation_id: UUID) -> ScreenDelivery | None: ...

    async def get(self, token: str, *, lock: bool = False) -> ScreenDelivery | None: ...

    async def latest(self, session_id: UUID, revision: int) -> ScreenDelivery | None: ...

    async def create(self, delivery: ScreenDelivery) -> None: ...

    async def set_status(
        self,
        token: str,
        status: DeliveryStatus,
        message_id: int | None = None,
        *,
        message_ids: tuple[int, ...] | None = None,
    ) -> None: ...


class LocationStore(Protocol):
    async def observe(self, user_id: int, chat_id: int, update_id: int, handler: str, state: str | None) -> None: ...

    async def forget_legacy(self) -> None: ...


class MaintenanceStore(Protocol):
    async def purge_closed(self, before: datetime) -> tuple[int, int]: ...
